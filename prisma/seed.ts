async function main() {
  console.log(`🌱 Seeding ${BANGLADESHI_FOODS.length} authentic Bangladeshi food items...`);

  for (const food of BANGLADESHI_FOODS) {
    await prisma.foodItem.upsert({
      where: { id: `food-${food.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}` },
      update: {
        name: food.name,
        bengaliName: food.bengaliName,
        category: food.category,
        servingQty: food.servingQty,
        unitWeightG: food.unitWeightG,
        kcal: food.kcal,
        proteinG: food.proteinG,
        carbsG: food.carbsG,
        fatG: food.fatG,
        keywords: food.keywords,
        isVerified: true,
      },
      create: {
        id: `food-${food.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
        name: food.name,
        bengaliName: food.bengaliName,
        category: food.category,
        servingQty: food.servingQty,
        unitWeightG: food.unitWeightG,
        kcal: food.kcal,
        proteinG: food.proteinG,
        carbsG: food.carbsG,
        fatG: food.fatG,
        keywords: food.keywords,
        isVerified: true,
      },
    });
  }

  // Create a default seed user for test/demo if needed
  const demoEmail = 'testuser@nutripath.com';
  const existingUser = await prisma.user.findUnique({ where: { email: demoEmail } });
  if (!existingUser) {
    await prisma.user.create({
      data: {
        id: 'demo-user-uuid-1',
        email: demoEmail,
        name: 'Demo Bangladeshi User',
        gender: 'MALE',
        age: 26,
        heightCm: 175.0,
        currentWeight: 110.0,
        targetWeight: 100.0,
        targetMonths: 2,
        activityLevel: 'COMMUTE',
        healthConditions: ['None'],
        kcalOverride: 1200,
        isDarkTheme: false,
        isOnboarded: true,
      },
    });
    console.log(`👤 Created default demo user: ${demoEmail}`);
  }

  console.log('✅ Seed completed successfully!');
}

main()
  .catch((e) => {
    console.error('❌ Error during seeding:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
